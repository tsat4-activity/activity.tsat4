// Add the Planner to an activity that already runs, and copy its old Gantt plan (mt_<key>_plan) once:
// one main item per (year, title); a title with one date range keeps its dates, several ranges become sub items.
//   node scripts/act-sql.js 5s --add-task -> db/act/5s_task.sql
export function actTaskSql(activity) {
  if (!ACTIVITIES.includes(activity)) throw new Error(`unknown activity ${activity}`);
  const k = activity.replace(/[^a-z0-9]/g, '');
  return `-- กิจกรรม ${activity}: เพิ่ม Project Planner ให้ฐานที่ใช้งานอยู่ — รันใน **Tx Data** (รันซ้ำได้) · สร้างจาก scripts/act-sql.js ห้ามแก้มือ
-- คัดลอกแผน Gantt เดิม (mt_${k}_plan ถ้ามี) เข้า Planner ครั้งเดียว ตอนที่ mt_${k}_task ยังว่าง (ไม่ลบแผนเดิม)
${taskTableSql(activity, k)}
do $$ begin
  if to_regclass('public.mt_${k}_plan') is not null and not exists (select 1 from public.mt_${k}_task) then
    with g as (
      select extract(year from start_date)::int as year, title, count(*) as n, min(start_date) as first_start,
        min(start_date) as start_date, max(end_date) as end_date,
        bool_and(status = 'done') as done, min(created_by) as created_by, max(responsible) as responsible, max(detail) as detail
      from public.mt_${k}_plan where status <> 'cancelled'
      group by 1, 2
    )
    insert into public.mt_${k}_task (year, sort_no, title, start_date, end_date, progress, note, created_by)
    select year, row_number() over (partition by year order by first_start, title), title,
      case when n = 1 then start_date end, case when n = 1 then end_date end,
      case when n = 1 and done then 100 else 0 end,
      case when n = 1 then nullif(concat_ws(' · ', detail, 'ผู้รับผิดชอบ: ' || responsible), '') end,
      coalesce(created_by, 'import')
    from g;

    insert into public.mt_${k}_task (year, parent_id, sort_no, title, start_date, end_date, progress, note, created_by)
    select t.year, t.id, row_number() over (partition by t.id order by p.start_date, p.id), p.title, p.start_date, p.end_date,
      case when p.status = 'done' then 100 else 0 end,
      nullif(concat_ws(' · ', p.detail, 'ผู้รับผิดชอบ: ' || p.responsible), ''), p.created_by
    from public.mt_${k}_plan p
    join public.mt_${k}_task t on t.parent_id is null and t.title = p.title and t.year = extract(year from p.start_date)::int and t.start_date is null
    where p.status <> 'cancelled';
  end if;
end $$;

${'alter table public.mt_' + k + '_task enable row level security;'}

-- ตรวจ: main / sub = ข้อหลัก / ข้อรองใน Planner (เทียบกับแผนเดิมใน mt_${k}_plan ที่ไม่ได้ยกเลิก)
select (select count(*) from public.mt_${k}_task where parent_id is null) as main,
  (select count(*) from public.mt_${k}_task where parent_id is not null) as sub;

notify pgrst, 'reload schema';
`;
}

