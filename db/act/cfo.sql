-- ตารางอ้างอิง EF ตามแผ่น EF TGO AR5 V2 (ผู้ใช้กำหนด 2026-11-01) ไว้ดูและค้น ไม่ได้ใช้คำนวณตรง (กิจกรรมใช้ mt_cfo_ef)
-- sheet: energy = EF การใช้พลังงาน (ต่อหน่วย) · chemical = GWP สารเคมี / สารทำความเย็น · ipcc = EF จาก IPCC Guidelines (ต่อ TJ)
--   · fuel = คุณสมบัติเชื้อเพลิง (grp = Heating value / Density / Conversion Factor, ค่าอยู่ใน total)
--   · cfp = EF ของ CFP ไว้คำนวณย่อย (total = kgCO2-eq ต่อหน่วย, formula = รายละเอียด) ผู้ใช้กรอก / วางจาก Excel เอง
-- grp = หัวกลุ่ม (Stationary Source / Mobile Source / Electricity / Refrigerants) · แถวที่ไม่มีหน่วยและไม่มีค่า = หัวข้อย่อย
-- total = kgCO2-eq ต่อหน่วย (ว่าง + มีค่าแยกก๊าซ = server คิดจาก GWP) · ratio = สัดส่วนชีวมวล (B7 = 0.07) · ข้อมูลตั้งต้น db/act/cfo_ef_ref_seed.sql
create table if not exists public.mt_cfo_ef_ref (
  id bigint generated by default as identity primary key,
  sheet text not null,
  grp text,
  name text not null,
  formula text,
  unit text,
  co2 numeric, ch4_fossil numeric, ch4 numeric, n2o numeric,
  total numeric,
  ratio numeric,
  reference text,
  remark text,
  sort_no integer not null default 0,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
create index if not exists mt_cfo_ef_ref_sheet on public.mt_cfo_ef_ref (sheet, sort_no);
alter table public.mt_cfo_ef_ref drop constraint if exists mt_cfo_ef_ref_sheet_check;
alter table public.mt_cfo_ef_ref add constraint mt_cfo_ef_ref_sheet_check check (sheet in ('energy', 'chemical', 'ipcc', 'fuel', 'cfp'));
-- code = id ที่ผู้ใช้เห็นและกรอกในกิจกรรม / วัสดุ (ผู้ใช้กำหนด 2026-11-02, เริ่มที่ EF CFP: CFP-0001 …) · ไม่ซ้ำทั้งตาราง
-- item_no = ลำดับตามไฟล์ อบก. (เริ่มใหม่ทุกกลุ่ม) · ตาราง EF CFP เรียงคอลัมน์ตาม อบก.: กลุ่ม · ลำดับ · ชื่อ · รายละเอียด · หน่วย · ค่าแฟคเตอร์ · ข้อมูลอ้างอิง · วันที่อัพเดท (remark)
alter table public.mt_cfo_ef_ref add column if not exists code text, add column if not exists item_no text;
create unique index if not exists mt_cfo_ef_ref_code on public.mt_cfo_ef_ref (code) where code is not null;
update public.mt_cfo_ef_ref r set code = 'CFP-' || lpad((x.n + x.base)::text, 4, '0')
from (select id, row_number() over (order by sort_no, id) as n,
        coalesce((select max(substring(code from 5)::int) from public.mt_cfo_ef_ref where code ~ '^CFP-[0-9]+$'), 0) as base
      from public.mt_cfo_ef_ref where sheet = 'cfp' and code is null) x
where r.id = x.id;
-- id ของ EF ตามเอกสาร อบก. "ค่าการปล่อยก๊าซเรือนกระจก ... คาร์บอนฟุตพริ้นท์ขององค์กร" (ผู้ใช้กำหนด 2026-11-02): EF พลังงาน แล้ว GWP สารเคมี
-- เรียงตามเอกสาร CFO-0001 … · เฉพาะแถวที่มีหน่วยและค่า (หัวข้อไม่มี id) · แถวใหม่ต่อเลขเดิม
update public.mt_cfo_ef_ref r set code = 'CFO-' || lpad((x.n + x.base)::text, 4, '0')
from (select id, row_number() over (order by case sheet when 'energy' then 1 else 2 end, sort_no, id) as n,
        coalesce((select max(substring(code from 5)::int) from public.mt_cfo_ef_ref where code ~ '^CFO-[0-9]+$'), 0) as base
      from public.mt_cfo_ef_ref where sheet in ('energy', 'chemical') and code is null and unit is not null and total is not null) x
where r.id = x.id;

-- วัสดุจาก SAP (Store usage, Scope 3 ผู้ใช้กำหนด 2026-11-01): รายการวัสดุ + EF ที่จับคู่ (ตารางอ้างอิง) + ตัวแปลงหน่วย
-- factor = 1 หน่วย SAP เท่ากับกี่หน่วยของ EF (เช่น กระดาษ A4 80g 1 รีม = 2.495 kg) · ไม่มี EF = ไม่คิด
-- รายการตั้งต้นจาก inbox/import_cfo_material.sql (scripts/import_cfo_material.py อ่าน master_sto.xlsx)
create table if not exists public.mt_cfo_material (
  material text primary key,                              -- รหัส SAP (ตัด 0 นำหน้า)
  name text not null,
  sap_unit text,
  price numeric,
  ef_ref_id bigint references public.mt_cfo_ef_ref (id) on delete set null,
  factor numeric check (factor > 0),
  scope_code text not null default '3-1' references public.mt_cfo_scope (code) check (scope_code like '3-%'),
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- Usage รายเดือนจาก SAP ที่คิดได้ (รวมต่อ เดือน × หน่วยงาน × วัสดุ) · เก็บ EF / ตัวแปลง ณ ตอนวาง ผลย้อนหลังไม่เปลี่ยน
-- วางเดือนเดิมซ้ำ = แทนที่ทั้งเดือน · qty = หน่วย SAP · tco2e = qty × factor × kgco2e / 1000
create table if not exists public.tx_cfo_material (
  id bigint generated by default as identity primary key,
  month date not null check (extract(day from month) = 1),
  department text,
  material text not null,
  name text,
  qty numeric not null check (qty >= 0),
  unit text,
  factor numeric not null,
  ef_ref_id bigint,
  source text not null,
  ef_unit text,
  kgco2e numeric not null,
  scope_code text not null references public.mt_cfo_scope (code),
  tco2e numeric not null,
  uploaded_by text not null,
  uploaded_at timestamptz not null default now()
);
create index if not exists tx_cfo_material_month on public.tx_cfo_material (month);
-- ประเภทวัสดุ (ผู้ใช้กำหนด 2026-11-02): usage = ของใช้สิ้นเปลือง (Store usage) · raw = วัตถุดิบ (เหล็ก ...) · other = อื่นๆ
alter table public.mt_cfo_material add column if not exists kind text not null default 'usage';
alter table public.mt_cfo_material drop constraint if exists mt_cfo_material_kind;
alter table public.mt_cfo_material add constraint mt_cfo_material_kind check (kind in ('usage', 'raw', 'other'));
alter table public.tx_cfo_material add column if not exists kind text not null default 'usage';
-- รายงาน Usage ต่อ costcenter (ผู้ใช้กำหนด 2026-11-02): costcenter ตามไฟล์ SAP (department = section ของ costcenter) · amount = เงิน (บาท)
alter table public.tx_cfo_material add column if not exists costcenter text;
alter table public.tx_cfo_material add column if not exists amount numeric;
create index if not exists tx_cfo_material_cc on public.tx_cfo_material (month, costcenter);

-- กิจกรรมที่ต้องเก็บข้อมูลทุกเดือน (รถผู้บริหาร, Forklift, ไฟฟ้า ...) ของหน่วยงานไหน ใช้ EF ตัวไหน
create table if not exists public.mt_cfo_activity (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (ac1051026-001)
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  department text not null,
  name text not null,
  detail text,
  calc text,                                              -- สูตรปริมาณ (server CFO_CALCS): septic / tkm / km_fuel · ว่าง = กรอกเอง
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
-- septic = บ่อเกรอะ (คน × วัน → kg CH4) · tkm = ขนส่ง (ตัน × กม.) · km_fuel = ระยะทาง ÷ กม./ลิตร → ลิตร
alter table public.mt_cfo_activity drop constraint if exists mt_cfo_activity_calc_check;
alter table public.mt_cfo_activity add constraint mt_cfo_activity_calc_check check (calc in ('septic', 'tkm', 'km_fuel'));

-- ข้อมูลรายเดือน 1 แถว = 1 กิจกรรม × 1 เดือน · ef_id / gwp_code = ค่าที่ใช้ตอนบันทึก (คัดลอกจากกิจกรรม)
create table if not exists public.tx_cfo_entry (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.mt_cfo_activity (id),
  month date not null check (extract(day from month) = 1),
  qty numeric not null check (qty >= 0),
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  inputs jsonb,                                           -- ค่าที่กรอกให้สูตร calc เช่น {"people": 250, "days": 26}
  doc text,                                               -- ลิงก์เอกสาร/รูปหลักฐาน (bucket img_cfo)
  status text not null default 'DRAFT' check (status in ('DRAFT', 'CONFIRMED')),
  remark text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz,
  unique (activity_id, month)
);
create index if not exists tx_cfo_entry_month on public.tx_cfo_entry (month);

